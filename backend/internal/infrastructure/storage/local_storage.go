package storage

import (
	"errors"
	"fmt"
	"io"
	"mime/multipart"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"strings"
	"time"

	"github.com/google/uuid"
)

const MaxUploadBytes int64 = 10 << 20 // 10 MiB

var ErrInvalidUpload = errors.New("invalid upload")
var ErrInvalidStoredPath = errors.New("invalid stored path")

// allowedExtensions deliberately excludes formats that a browser can execute
// directly (HTML, SVG, JavaScript). Uploaded files are served from the app's
// authenticated file endpoints, but executable formats remain disallowed.
var allowedExtensions = map[string]bool{
	".pdf": true, ".png": true, ".jpg": true, ".jpeg": true, ".webp": true,
	".txt": true, ".csv": true, ".docx": true, ".xlsx": true, ".pptx": true,
}

type LocalStorage struct {
	BaseDir     string
	claimSecret []byte
}

func NewLocalStorage(baseDir string, claimSecret ...string) *LocalStorage {
	if baseDir == "" {
		baseDir = "./uploads"
	}
	store := &LocalStorage{BaseDir: baseDir}
	if len(claimSecret) > 0 {
		store.claimSecret = []byte(claimSecret[0])
	}
	return store
}

func (s *LocalStorage) Save(file multipart.File, header *multipart.FileHeader, orgID string) (string, error) {
	parsedOrgID, err := uuid.Parse(orgID)
	if err != nil || parsedOrgID == uuid.Nil {
		return "", fmt.Errorf("%w: invalid organization", ErrInvalidUpload)
	}
	if header == nil || header.Filename == "" {
		return "", fmt.Errorf("%w: file is required", ErrInvalidUpload)
	}
	if header.Size <= 0 {
		return "", fmt.Errorf("%w: file is empty", ErrInvalidUpload)
	}
	if header.Size > MaxUploadBytes {
		return "", fmt.Errorf("%w: file exceeds the 10 MB limit", ErrInvalidUpload)
	}

	ext := strings.ToLower(filepath.Ext(header.Filename))
	if !allowedExtensions[ext] {
		return "", fmt.Errorf("%w: unsupported file type", ErrInvalidUpload)
	}

	// Do not trust the multipart Content-Type supplied by a client. Sniff the
	// actual content and restore the stream before persisting it.
	buf := make([]byte, 512)
	n, err := file.Read(buf)
	if err != nil && !errors.Is(err, io.EOF) {
		return "", fmt.Errorf("%w: could not inspect file", ErrInvalidUpload)
	}
	if _, err := file.Seek(0, io.SeekStart); err != nil {
		return "", fmt.Errorf("%w: could not read file", ErrInvalidUpload)
	}
	detectedType := http.DetectContentType(buf[:n])
	if !isAllowedContentType(ext, detectedType) {
		return "", fmt.Errorf("%w: file content does not match an allowed type", ErrInvalidUpload)
	}

	orgDir := filepath.Join(s.BaseDir, parsedOrgID.String())
	if err := os.MkdirAll(orgDir, 0700); err != nil {
		return "", fmt.Errorf("failed to create upload directory: %w", err)
	}

	storedName := fmt.Sprintf("%s_%d%s", uuid.New().String(), time.Now().UnixMilli(), ext)
	storedPath := filepath.Join(orgDir, storedName)

	dst, err := os.OpenFile(storedPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return "", fmt.Errorf("failed to create file: %w", err)
	}
	defer dst.Close()

	if _, err := io.Copy(dst, file); err != nil {
		return "", fmt.Errorf("failed to save file: %w", err)
	}

	// Return relative path for serving
	return filepath.Join("uploads", parsedOrgID.String(), storedName), nil
}

// ResolvePrivatePath translates a database-stored upload path to an on-disk
// path only when it belongs to the requesting tenant. It deliberately accepts
// the narrow shape generated by Save: uploads/<org UUID>/<filename>. This is
// safe to use from an authenticated download handler and rejects traversal,
// absolute paths, and files from another organization.
func (s *LocalStorage) ResolvePrivatePath(orgID, storedPath string) (string, error) {
	parsedOrgID, err := uuid.Parse(orgID)
	if err != nil || parsedOrgID == uuid.Nil {
		return "", ErrInvalidStoredPath
	}

	cleaned := path.Clean(strings.TrimSpace(storedPath))
	prefix := "uploads/" + parsedOrgID.String() + "/"
	if strings.HasPrefix(cleaned, "/") || !strings.HasPrefix(cleaned, prefix) {
		return "", ErrInvalidStoredPath
	}
	fileName := strings.TrimPrefix(cleaned, prefix)
	if fileName == "" || fileName != path.Base(fileName) || fileName == "." || fileName == ".." {
		return "", ErrInvalidStoredPath
	}

	base, err := filepath.Abs(s.BaseDir)
	if err != nil {
		return "", fmt.Errorf("resolve upload directory: %w", err)
	}
	resolved, err := filepath.Abs(filepath.Join(base, parsedOrgID.String(), filepath.FromSlash(fileName)))
	if err != nil {
		return "", fmt.Errorf("resolve upload file: %w", err)
	}
	relative, err := filepath.Rel(base, resolved)
	if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) || filepath.IsAbs(relative) {
		return "", ErrInvalidStoredPath
	}
	// Existing upload trees may contain files from before private permissions
	// were introduced. Do not follow a symlink planted in that tree.
	for _, candidate := range []string{base, filepath.Join(base, parsedOrgID.String()), resolved} {
		info, statErr := os.Lstat(candidate)
		if statErr == nil && info.Mode()&os.ModeSymlink != 0 {
			return "", ErrInvalidStoredPath
		}
		if statErr != nil && !errors.Is(statErr, os.ErrNotExist) {
			return "", ErrInvalidStoredPath
		}
	}
	return resolved, nil
}

// PromoteAvatar moves a freshly uploaded image into a user-specific public
// namespace. Course uploads can never be resolved through this namespace.
func (s *LocalStorage) PromoteAvatar(orgID, userID, storedPath string) (string, error) {
	parsedUserID, err := uuid.Parse(userID)
	if err != nil || parsedUserID == uuid.Nil || !isAvatarExtension(filepath.Ext(storedPath)) {
		return "", ErrInvalidStoredPath
	}
	source, err := s.ResolvePrivatePath(orgID, storedPath)
	if err != nil {
		return "", err
	}
	dir := filepath.Join(s.BaseDir, "avatars", parsedUserID.String())
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", err
	}
	name := filepath.Base(source)
	destination := filepath.Join(dir, name)
	if err := os.Rename(source, destination); err != nil {
		return "", err
	}
	if err := os.Chmod(destination, 0644); err != nil {
		return "", err
	}
	return path.Join("avatars", parsedUserID.String(), name), nil
}

func (s *LocalStorage) ResolvePublicAvatarPath(userID, storedPath string) (string, error) {
	parsedUserID, err := uuid.Parse(userID)
	if err != nil || parsedUserID == uuid.Nil {
		return "", ErrInvalidStoredPath
	}
	prefix := "avatars/" + parsedUserID.String() + "/"
	if !strings.HasPrefix(storedPath, prefix) {
		return "", ErrInvalidStoredPath
	}
	name := strings.TrimPrefix(storedPath, prefix)
	if name == "" || name != path.Base(name) || !isAvatarExtension(path.Ext(name)) {
		return "", ErrInvalidStoredPath
	}
	base, err := filepath.Abs(s.BaseDir)
	if err != nil {
		return "", err
	}
	resolved := filepath.Join(base, "avatars", parsedUserID.String(), name)
	for _, candidate := range []string{base, filepath.Join(base, "avatars"), filepath.Join(base, "avatars", parsedUserID.String()), resolved} {
		info, statErr := os.Lstat(candidate)
		if statErr != nil || info.Mode()&os.ModeSymlink != 0 {
			return "", ErrInvalidStoredPath
		}
	}
	return resolved, nil
}

func isAvatarExtension(ext string) bool {
	switch strings.ToLower(ext) {
	case ".png", ".jpg", ".jpeg", ".webp":
		return true
	default:
		return false
	}
}

func isAllowedContentType(ext, contentType string) bool {
	switch ext {
	case ".pdf":
		return contentType == "application/pdf"
	case ".png":
		return contentType == "image/png"
	case ".jpg", ".jpeg":
		return contentType == "image/jpeg"
	case ".webp":
		return contentType == "image/webp"
	case ".txt", ".csv":
		return strings.HasPrefix(contentType, "text/") || contentType == "application/octet-stream"
	case ".docx", ".xlsx", ".pptx":
		// Office Open XML documents are ZIP containers. Their precise browser
		// upload MIME varies, but executable formats are never in this allowlist.
		return contentType == "application/zip" || contentType == "application/octet-stream"
	default:
		return false
	}
}
